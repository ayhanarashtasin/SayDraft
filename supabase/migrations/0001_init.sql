CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS notes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL DEFAULT '',
  transcript TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'ready' CHECK (status IN ('uploading', 'processing', 'ready', 'failed')),
  stage TEXT,
  progress DOUBLE PRECISION,
  error TEXT,
  source TEXT NOT NULL DEFAULT 'text' CHECK (source IN ('recording', 'meeting', 'upload', 'text', 'merge')),
  language TEXT,
  speakers BOOLEAN NOT NULL DEFAULT FALSE,
  archived BOOLEAN NOT NULL DEFAULT FALSE,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_notes_updated ON notes (archived, updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_notes_created ON notes (archived, created_at DESC);

CREATE TABLE IF NOT EXISTS audio_files (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  note_id BIGINT NOT NULL REFERENCES notes (id) ON DELETE CASCADE,
  file_name TEXT NOT NULL,
  mime TEXT NOT NULL,
  size BIGINT NOT NULL,
  duration_sec DOUBLE PRECISION,
  original_name TEXT,
  position INTEGER NOT NULL,
  prepared BOOLEAN NOT NULL DEFAULT FALSE,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'ready', 'failed')),
  transcript TEXT,
  created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_audio_files_note ON audio_files (note_id, position);

CREATE TABLE IF NOT EXISTS tags (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  color TEXT NOT NULL,
  position INTEGER NOT NULL DEFAULT 0,
  created_at BIGINT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_tags_title_lower ON tags (LOWER(title));

CREATE TABLE IF NOT EXISTS note_tags (
  note_id BIGINT NOT NULL REFERENCES notes (id) ON DELETE CASCADE,
  tag_id BIGINT NOT NULL REFERENCES tags (id) ON DELETE CASCADE,
  PRIMARY KEY (note_id, tag_id)
);
CREATE INDEX IF NOT EXISTS idx_note_tags_tag ON note_tags (tag_id);

CREATE TABLE IF NOT EXISTS prompts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  category TEXT NOT NULL DEFAULT 'Custom',
  body TEXT NOT NULL,
  properties JSONB NOT NULL DEFAULT '[]'::jsonb,
  model TEXT,
  builtin_key TEXT UNIQUE,
  template_id TEXT,
  is_favorite BOOLEAN NOT NULL DEFAULT FALSE,
  position INTEGER NOT NULL DEFAULT 0,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS rewrites (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  note_id BIGINT NOT NULL REFERENCES notes (id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('rewrite', 'translation', 'instruction')),
  prompt_id BIGINT REFERENCES prompts (id) ON DELETE SET NULL,
  label TEXT NOT NULL,
  language TEXT,
  instruction TEXT,
  source_rewrite_id BIGINT,
  status TEXT NOT NULL DEFAULT 'ready' CHECK (status IN ('processing', 'ready', 'failed')),
  error TEXT,
  text TEXT NOT NULL DEFAULT '',
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_rewrites_note ON rewrites (note_id, created_at DESC);

CREATE TABLE IF NOT EXISTS dictionary (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  word TEXT NOT NULL,
  created_at BIGINT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_dictionary_word_lower ON dictionary (LOWER(word));

CREATE TABLE IF NOT EXISTS replacements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  find TEXT NOT NULL,
  replace_with TEXT NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at BIGINT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_replacements_find_lower ON replacements (LOWER(find));

CREATE TABLE IF NOT EXISTS actions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type TEXT NOT NULL CHECK (type IN ('webhook', 'notion')),
  title TEXT NOT NULL,
  config JSONB NOT NULL DEFAULT '{}'::jsonb,
  on_transcript BOOLEAN NOT NULL DEFAULT FALSE,
  on_rewrite BOOLEAN NOT NULL DEFAULT FALSE,
  last_status TEXT,
  last_error TEXT,
  last_run_at BIGINT,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL
);

